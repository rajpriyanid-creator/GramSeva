/**
 * Returns localized name for a scheme or falls back to native properties / English name
 */
export function getTranslatedSchemeName(scheme: any, langCode: string): string {
  if (!scheme) return "";
  const tMap = SCHEME_TRANSLATIONS[langCode];
  if (tMap && tMap[scheme.id]) {
    return tMap[scheme.id];
  }
  // Database fields fallback
  const langKey = langCode.split("-")[0];
  const dbProp = `name_${langKey}`;
  if (scheme[dbProp]) {
    return scheme[dbProp];
  }
  return scheme.name || "";
}
